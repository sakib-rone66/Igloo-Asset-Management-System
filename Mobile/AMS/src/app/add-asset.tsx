// src/app/add-asset.tsx

import React, { useEffect, useState } from "react";
import {
  ActivityIndicator,
  Alert,
  KeyboardAvoidingView,
  Platform,
  ScrollView,
  StyleSheet,
  Text,
  TextInput,
  TouchableOpacity,
  View,
} from "react-native";
import { SafeAreaView } from "react-native-safe-area-context";
import { Ionicons } from "@expo/vector-icons";
import { router } from "expo-router";
import {
  Colors,
  Radius,
  Shadows,
  Spacing,
  Typography,
} from "../constants/theme";
import { authorizationApi, outletApi } from "../services/api";
import { Manufacturer } from "../services/apiTypes";

export default function AddAssetScreen() {
  const [capacity, setCapacity] = useState("");
  const [manufacturingMonth, setManufacturingMonth] = useState("");
  const [manufacturingYear, setManufacturingYear] = useState("");

  const [manufacturers, setManufacturers] = useState<Manufacturer[]>([]);
  const [selectedManufacturer, setSelectedManufacturer] =
    useState<Manufacturer | null>(null);
  const [loading, setLoading] = useState(true);
  const [submitting, setSubmitting] = useState(false);

  useEffect(() => {
    outletApi
      .getManufacturers()
      .then((res: any) => {
        const list = res.manufacturers || res || [];
        setManufacturers(list);
        if (list.length > 0) {
          setSelectedManufacturer(list[0]);
        }
      })
      .catch((err) => console.error("Failed to load manufacturers:", err))
      .finally(() => setLoading(false));
  }, []);

  const handleSubmit = async () => {
    if (!selectedManufacturer) {
      Alert.alert("Manufacturer Required", "Please select a manufacturer.");
      return;
    }

    const capNum = parseInt(capacity, 10);
    const monthNum = parseInt(manufacturingMonth, 10);
    const yearNum = parseInt(manufacturingYear, 10);

    if (!capNum || capNum <= 0) {
      Alert.alert(
        "Invalid Capacity",
        "Please enter a valid capacity in liters.",
      );
      return;
    }

    if (!monthNum || monthNum < 1 || monthNum > 12) {
      Alert.alert(
        "Invalid Month",
        "Please enter a manufacturing month between 1 and 12.",
      );
      return;
    }

    const currentYear = new Date().getFullYear();
    if (!yearNum || yearNum < 2000 || yearNum > currentYear) {
      Alert.alert(
        "Invalid Year",
        `Please enter a manufacturing year between 2000 and ${currentYear}.`,
      );
      return;
    }

    try {
      setSubmitting(true);
      await authorizationApi.createAssetAuthorization({
        manufacturer: selectedManufacturer._id,
        capacity: capNum,
        manufacturingMonth: monthNum,
        manufacturingYear: yearNum,
      });

      Alert.alert(
        "Asset Registered",
        "The asset request was submitted for authorization. AIN and serial number will be generated after approval.",
        [{ text: "Done", onPress: () => router.back() }],
      );
    } catch (err: any) {
      Alert.alert(
        "Registration Error",
        err?.message || "Could not register asset.",
      );
    } finally {
      setSubmitting(false);
    }
  };

  return (
    <SafeAreaView style={styles.safeArea}>
      <View style={styles.header}>
        <TouchableOpacity onPress={() => router.back()} hitSlop={10}>
          <Ionicons name="arrow-back" size={24} color={Colors.light.text} />
        </TouchableOpacity>
        <Text style={styles.headerTitle}>Register New Asset</Text>
        <View style={{ width: 24 }} />
      </View>

      <KeyboardAvoidingView
        style={{ flex: 1 }}
        behavior={Platform.OS === "ios" ? "padding" : undefined}
      >
        <ScrollView
          style={styles.container}
          contentContainerStyle={styles.content}
          showsVerticalScrollIndicator={false}
          keyboardShouldPersistTaps="handled"
        >
          <View style={styles.card}>
            <Text style={styles.sectionTitle}>Freezer Specifications</Text>
            <Text style={styles.sectionSubtitle}>
              Add a new freezer asset into central warehouse inventory
            </Text>

            <View style={styles.infoBanner}>
              <Ionicons
                name="information-circle-outline"
                size={20}
                color={Colors.light.info}
              />
              <Text style={styles.infoBannerText}>
                AIN and serial number are generated by the system after
                authorization approval.
              </Text>
            </View>

            {/* MANUFACTURER SELECTION */}
            <Text style={[styles.inputLabel, { marginTop: Spacing.md }]}>
              MANUFACTURER *
            </Text>
            {loading ? (
              <ActivityIndicator size="small" color={Colors.light.primary} />
            ) : (
              <ScrollView
                horizontal
                showsHorizontalScrollIndicator={false}
                style={styles.chipRow}
              >
                {manufacturers.map((m) => {
                  const isSelected = selectedManufacturer?._id === m._id;
                  return (
                    <TouchableOpacity
                      key={m._id}
                      style={[styles.chip, isSelected && styles.chipActive]}
                      onPress={() => setSelectedManufacturer(m)}
                    >
                      <Text
                        style={[
                          styles.chipText,
                          isSelected && styles.chipTextActive,
                        ]}
                      >
                        {m.name}
                      </Text>
                    </TouchableOpacity>
                  );
                })}
              </ScrollView>
            )}

            {/* CAPACITY */}
            <Text style={[styles.inputLabel, { marginTop: Spacing.md }]}>
              CAPACITY (LITERS) *
            </Text>
            <TextInput
              style={styles.input}
              placeholder="e.g. 200, 300, 500"
              placeholderTextColor={Colors.light.textMuted}
              value={capacity}
              onChangeText={setCapacity}
              keyboardType="numeric"
            />

            {/* MANUFACTURE MONTH & YEAR */}
            <View style={styles.dateRow}>
              <View style={{ flex: 1 }}>
                <Text style={styles.inputLabel}>MONTH (1-12)</Text>
                <TextInput
                  style={styles.input}
                  value={manufacturingMonth}
                  onChangeText={setManufacturingMonth}
                  keyboardType="numeric"
                />
              </View>

              <View style={{ flex: 1 }}>
                <Text style={styles.inputLabel}>YEAR</Text>
                <TextInput
                  style={styles.input}
                  value={manufacturingYear}
                  onChangeText={setManufacturingYear}
                  keyboardType="numeric"
                />
              </View>
            </View>

            {/* SUBMIT BUTTON */}
            <TouchableOpacity
              style={[styles.submitBtn, submitting && styles.btnDisabled]}
              onPress={handleSubmit}
              disabled={submitting}
            >
              {submitting ? (
                <ActivityIndicator color={Colors.light.white} />
              ) : (
                <>
                  <Ionicons
                    name="add-circle-outline"
                    size={20}
                    color={Colors.light.white}
                  />
                  <Text style={styles.submitBtnText}>
                    Submit for Authorization
                  </Text>
                </>
              )}
            </TouchableOpacity>
          </View>
        </ScrollView>
      </KeyboardAvoidingView>
    </SafeAreaView>
  );
}

